/**
 * Script to geocode all VCAN distribution addresses once
 * Run this script once to generate coordinates, then copy them to vcanDistributionCoordinates.ts
 * 
 * Usage: node scripts/geocode-vcan-addresses.js
 * 
 * Requires: MAPBOX_ACCESS_TOKEN environment variable
 */

const fs = require('fs');
const path = require('path');

// Import address lists (simplified version for Node.js)
const AIR_FILTER_ADDRESSES = [
  '149 Bellbridge Rd 15133',
  '1159 Lovedale Rd 15133',
  'Lincoln Blvd 15133',
  '3918 Liberty Way 15133',
  // ... (all addresses from the service file)
];

const AIR_PURIFIER_ADDRESSES = [
  // ... (all addresses from the service file)
];

function parseAddress(addressStr) {
  const cleaned = addressStr.trim();
  const zipMatch = cleaned.match(/(\d{5})/);
  const zipCode = zipMatch ? zipMatch[1] : '';
  
  let city = '';
  if (cleaned.includes('Clairton')) {
    city = 'Clairton';
  } else if (cleaned.includes('McKeesport') || cleaned.match(/15(132|133)/)) {
    city = 'McKeesport';
  } else if (cleaned.includes('Monongahela') || cleaned.match(/15045/)) {
    city = 'Monongahela';
  } else {
    city = 'Mon Valley';
  }
  
  const street = cleaned.replace(/\s*(Clairton|McKeesport|Monongahela|Mon Valley).*/, '').trim();
  
  return { street, city, zipCode };
}

async function geocodeAddress(address, city, zipCode, mapboxToken) {
  const fullAddress = `${address}, ${city}, PA ${zipCode}, USA`;
  
  try {
    const response = await fetch(
      `https://api.mapbox.com/geocoding/v5/mapbox.places/${encodeURIComponent(fullAddress)}.json?access_token=${mapboxToken}&limit=1&country=us&proximity=-79.88,40.30`
    );

    if (!response.ok) {
      console.warn(`Geocoding failed for ${fullAddress}: ${response.statusText}`);
      return null;
    }

    const data = await response.json();
    
    if (data.features && data.features.length > 0) {
      const [lng, lat] = data.features[0].center;
      return { lat, lng };
    }
    
    return null;
  } catch (error) {
    console.error(`Error geocoding ${address}:`, error.message);
    return null;
  }
}

async function geocodeAllAddresses() {
  const mapboxToken = process.env.MAPBOX_ACCESS_TOKEN || process.env.VITE_MAPBOX_ACCESS_TOKEN;
  
  if (!mapboxToken) {
    console.error('❌ MAPBOX_ACCESS_TOKEN environment variable not set');
    process.exit(1);
  }

  const filterCoords = {};
  const purifierCoords = {};

  // Geocode air filter addresses
  console.log('Geocoding air filter addresses...');
  for (let i = 0; i < AIR_FILTER_ADDRESSES.length; i++) {
    const addressStr = AIR_FILTER_ADDRESSES[i];
    const parsed = parseAddress(addressStr);
    const addressKey = `${parsed.street || addressStr}, ${parsed.city}, ${parsed.zipCode}`;
    
    console.log(`[${i + 1}/${AIR_FILTER_ADDRESSES.length}] ${addressKey}`);
    
    const coords = await geocodeAddress(parsed.street || addressStr, parsed.city, parsed.zipCode, mapboxToken);
    if (coords) {
      filterCoords[addressKey] = coords;
    }
    
    // Rate limit: 100ms delay between requests
    await new Promise(resolve => setTimeout(resolve, 100));
  }

  // Geocode air purifier addresses
  console.log('\nGeocoding air purifier addresses...');
  for (let i = 0; i < AIR_PURIFIER_ADDRESSES.length; i++) {
    const addressStr = AIR_PURIFIER_ADDRESSES[i];
    const parsed = parseAddress(addressStr);
    const addressKey = `${parsed.street || addressStr}, ${parsed.city}, ${parsed.zipCode}`;
    
    console.log(`[${i + 1}/${AIR_PURIFIER_ADDRESSES.length}] ${addressKey}`);
    
    const coords = await geocodeAddress(parsed.street || addressStr, parsed.city, parsed.zipCode, mapboxToken);
    if (coords) {
      purifierCoords[addressKey] = coords;
    }
    
    // Rate limit: 100ms delay between requests
    await new Promise(resolve => setTimeout(resolve, 100));
  }

  // Generate TypeScript code
  const filterCode = Object.entries(filterCoords)
    .map(([key, value]) => `  "${key}": { lat: ${value.lat}, lng: ${value.lng} },`)
    .join('\n');

  const purifierCode = Object.entries(purifierCoords)
    .map(([key, value]) => `  "${key}": { lat: ${value.lat}, lng: ${value.lng} },`)
    .join('\n');

  const output = `/**
 * Hardcoded geocoded coordinates for VCAN distribution addresses
 * Generated by scripts/geocode-vcan-addresses.js
 * DO NOT EDIT MANUALLY - Regenerate using the script if addresses change
 */

export interface AddressCoordinates {
  [addressKey: string]: { lat: number; lng: number };
}

export const AIR_FILTER_COORDINATES: AddressCoordinates = {
${filterCode}
};

export const AIR_PURIFIER_COORDINATES: AddressCoordinates = {
${purifierCode}
};
`;

  // Write to file
  const outputPath = path.join(__dirname, '../frontend/src/services/vcanDistributionCoordinates.ts');
  fs.writeFileSync(outputPath, output, 'utf8');
  
  console.log(`\n✅ Geocoding complete!`);
  console.log(`   Air Filters: ${Object.keys(filterCoords).length}/${AIR_FILTER_ADDRESSES.length}`);
  console.log(`   Air Purifiers: ${Object.keys(purifierCoords).length}/${AIR_PURIFIER_ADDRESSES.length}`);
  console.log(`\n📝 Coordinates written to: ${outputPath}`);
}

geocodeAllAddresses().catch(console.error);

